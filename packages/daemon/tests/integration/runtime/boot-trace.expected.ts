/**
 * The literal traces `boot-trace.test.ts` compares a boot against. Read them top to bottom as the boot.
 *
 *  - `step: X` is a boot notice. `register #n` is `cleanups.push`, `register first #n` is `cleanups.unshift`,
 *    numbered in registration order; `release #n` is that same release running, and every line between it and
 *    the next `release` is what that release really did, written by the port it called:
 *    `<owner>.close|stop|shutdown|flush` on a subsystem, host adapter, carrier or the bound server,
 *    `disarm <owner>` for the function an `arm` returned, `unsubscribe states|events`, and
 *    `clear setInterval|setTimeout <ms>` for a timer the wiring made and the release clears. A release with
 *    no line is one with no port to name: #25 is the shutdown-begun flag (`releasing = true`).
 *  - `arm X` / `run X` / `refreshLocal X` is a job `start()` armed on a mounted subsystem.
 *  - Between `createSubsystems: construction begins` and `ends` are the timers and sweeps a subsystem starts
 *    WHILE it is built: the agenda waker; the agenda deadline sweep (`setInterval 300000` then
 *    `setTimeout 30000`); and the catalog member sweep, link reconcile and link refresh, each written by
 *    the real method as `first sweep: ...` (its immediate first run) followed by the `setInterval` that
 *    repeats it. The remaining `setInterval` / `setTimeout` lines are the other timers built in that stretch.
 *    The agenda resurfacer is off unless the configuration sets `attention.resurfaceAfterMinutes`, so it is
 *    in none of the four boots below; `CONSTRUCTION_WITH_THE_RESURFACER_ON` is the same stretch with it on.
 */

