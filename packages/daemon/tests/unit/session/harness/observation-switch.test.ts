import { describe, it } from 'bun:test';
import should from 'should';
import { projectObservedRuntime } from '../../../../src/lib/session/harness/observation.ts';
import { ClaudeTranscriptParser } from '../../../../src/lib/transcript/claude.ts';
import { CodexTranscriptParser } from '../../../../src/lib/transcript/codex.ts';

/**
 * A runtime switch made at an IDLE prompt must be observable before the next turn.
 *
 * The daemon switches a Claude session by typing `/model <id>` into it. Claude restates its model
 * only on an assistant turn's usage record, so reading usage alone left the switch unconfirmed until
 * somebody sent a message — and the composer said "switching…" for as long as nobody did. These
 * fixtures are the records Claude Code 2.1.281 and Codex 0.145 actually write, run through the real
 * parsers, so a change to either harness's spelling fails here rather than in a phone's chip.
 */

const BEFORE = '2026-09-25T18:30:00.000Z';
const SWITCHED = '2026-09-25T18:36:02.970Z';

const claudeRecord = (fields: Readonly<Record<string, unknown>>): string =>
  JSON.stringify({
    isSidechain: false,
    userType: 'external',
    entrypoint: 'cli',
    cwd: '/work',
    sessionId: 'fixture-session',
    version: '2.1.281',
    ...fields,
  });

/** The assistant turn that last stated the model, before any switch. */
const claudeTurn = (model: string, timestamp: string): string =>
  claudeRecord({
    type: 'assistant',
    uuid: `turn-${timestamp}`,
    timestamp,
    message: {
      id: `msg-${timestamp}`,
      role: 'assistant',
      model,
      content: [{ type: 'text', text: 'done' }],
      stop_reason: 'end_turn',
      usage: { input_tokens: 10, output_tokens: 5 },
    },
  });

/** The three records Claude Code writes when `/model <args>` is typed at its prompt. */
const claudeModelCommand = (args: string, answer: string, timestamp = SWITCHED): string[] => [
  claudeRecord({
    type: 'user',
    uuid: 'caveat',
    timestamp,
    isMeta: true,
    message: {
      role: 'user',
      content:
        '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>',
    },
  }),
  claudeRecord({
    type: 'user',
    uuid: 'command',
    timestamp,
    message: {
      role: 'user',
      content: `<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args>${args}</command-args>`,
    },
  }),
  claudeRecord({
    type: 'user',
    uuid: 'answer',
    timestamp,
    message: { role: 'user', content: answer },
  }),
];

const claude = (lines: readonly string[]) =>
  projectObservedRuntime(new ClaudeTranscriptParser().parse({ text: `${lines.join('\n')}\n` }).events);

const codex = (lines: readonly string[]) =>
  projectObservedRuntime(new CodexTranscriptParser().parse({ text: `${lines.join('\n')}\n` }).events);

const codexSettings = (model: string, effort: string, timestamp: string): string =>
  JSON.stringify({
    timestamp,
    type: 'event_msg',
    payload: {
      type: 'thread_settings_applied',
      thread_settings: { model, model_provider_id: 'openai', reasoning_effort: effort, personality: 'pragmatic' },
    },
  });

describe('observing a Claude Code /model switch at an idle prompt', () => {
  it('should observe the switched model from the command answer, before any new turn', async () => {
    // Act
    const observed = claude([
      claudeTurn('claude-sonnet-5', BEFORE),
      ...claudeModelCommand(
        'claude-opus-5-5',
        '<local-command-stdout>Set model to `Opus 5.5 (1M context)` and saved as your default for new sessions</local-command-stdout>',
      ),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-opus-5-5', at: SWITCHED });
  });

  it('should read the answer through the terminal styling some versions print', async () => {
    // Act
    const observed = claude([
      claudeTurn('claude-sonnet-5', BEFORE),
      ...claudeModelCommand(
        'claude-opus-5-5[1m]',
        '<local-command-stdout>Set model to \u001b[1mOpus 5.5 (1M context)\u001b[22m</local-command-stdout>',
      ),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-opus-5-5[1m]', at: SWITCHED });
  });

  it('should move the timestamp when the running model is selected again', async () => {
    // Re-selecting changes only the timestamp — and that change is the whole confirmation the
    // composer is waiting for.
    // Act
    const observed = claude([
      claudeTurn('claude-opus-5-5', BEFORE),
      ...claudeModelCommand(
        'claude-opus-5-5',
        '<local-command-stdout>Kept model as `Opus 5.5 (1M context)`</local-command-stdout>',
      ),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-opus-5-5', at: SWITCHED });
  });

  it('should take nothing from a /model command Claude refused', async () => {
    // Act
    const observed = claude([
      claudeTurn('claude-sonnet-5', BEFORE),
      ...claudeModelCommand(
        'no-such-model',
        '<local-command-stderr>Model not found: no-such-model</local-command-stderr>',
      ),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-sonnet-5', at: BEFORE });
  });

  it('should take nothing from an answer that is not a model confirmation', async () => {
    // Act
    const observed = claude([
      claudeTurn('claude-sonnet-5', BEFORE),
      ...claudeModelCommand('opus', '<local-command-stdout>Invalid model</local-command-stdout>'),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-sonnet-5', at: BEFORE });
  });

  it('should take nothing from a bare /model, whose picker prints only a display name', async () => {
    // Act
    const observed = claude([
      claudeTurn('claude-sonnet-5', BEFORE),
      ...claudeModelCommand('', '<local-command-stdout>Set model to `Opus 5.5 (1M context)`</local-command-stdout>'),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-sonnet-5', at: BEFORE });
  });

  it('should not let one answer confirm a command that an earlier answer already settled', async () => {
    // Arrange
    const [caveat, command, refusal] = claudeModelCommand(
      'claude-opus-5-5',
      '<local-command-stderr>Model not found</local-command-stderr>',
    );
    const unrelated = claudeRecord({
      type: 'user',
      uuid: 'later',
      timestamp: '2026-09-25T18:40:00.000Z',
      message: { role: 'user', content: '<local-command-stdout>Set model to `Opus 5.5`</local-command-stdout>' },
    });

    // Act
    const observed = claude([
      claudeTurn('claude-sonnet-5', BEFORE),
      caveat ?? '',
      command ?? '',
      refusal ?? '',
      unrelated,
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-sonnet-5', at: BEFORE });
  });

  it('should let the next assistant turn restate the model in its own spelling', async () => {
    // Arrange
    const LATER = '2026-09-25T18:40:00.000Z';

    // Act
    const observed = claude([
      ...claudeModelCommand(
        'claude-opus-5-5[1m]',
        '<local-command-stdout>Set model to `Opus 5.5 (1M context)`</local-command-stdout>',
      ),
      claudeTurn('claude-opus-5-5', LATER),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'claude-opus-5-5', at: LATER });
  });
});

describe('observing a Codex picker switch', () => {
  it('should observe a switched model and level from the applied thread settings', async () => {
    // Act
    const observed = codex([
      codexSettings('gpt-5.6-codex', 'medium', BEFORE),
      codexSettings('gpt-5.6-terra', 'high', SWITCHED),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'gpt-5.6-terra', reasoningEffort: 'high', at: SWITCHED });
  });

  it('should move the timestamp when the same model and level are applied again', async () => {
    // Act
    const observed = codex([
      codexSettings('gpt-5.6-terra', 'high', BEFORE),
      codexSettings('gpt-5.6-terra', 'high', SWITCHED),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'gpt-5.6-terra', reasoningEffort: 'high', at: SWITCHED });
  });

  it('should observe a level-only switch on the same model', async () => {
    // Act
    const observed = codex([
      codexSettings('gpt-5.6-terra', 'high', BEFORE),
      codexSettings('gpt-5.6-terra', 'low', SWITCHED),
    ]);

    // Assert
    should(observed).deepEqual({ model: 'gpt-5.6-terra', reasoningEffort: 'low', at: SWITCHED });
  });
});
