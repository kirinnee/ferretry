/**
 * The one place a fleet profile's credential becomes a value, and the only thing it is handed to is
 * the launch it was resolved for.
 *
 * ## What this is
 *
 * A profile can authenticate an account instead of a login: it binds an environment variable to
 * `${secret:NAME}`, the fleet manifest publishes that binding as a REFERENCE, and this resolves the
 * reference against the daemon's own store at the moment a pane is launched. `docs/secrets.md` is the
 * contract and `docs/fleet-env-profiles.md` is the feature.
 *
 * ## Why this may hold a vault when almost nothing may
 *
 * `SecretVault` is the only thing in the daemon that opens ciphertext, and until now exactly two
 * things held one: the redactor, which turns values into masks, and the use executor, which puts them
 * in a child's environment and returns only that child's scrubbed output. This is the third, and it
 * is the same kind of thing as the second — it produces an environment for one launch and returns it
 * to the launcher, which passes it straight to the terminal. It projects nothing, logs nothing, and caches
 * nothing. A method here that returned a value to a caller who was going to show it to somebody would delete the
 * property rather than extend it.
 *
 * ## The one narrow exception, in time and not in kind
 *
 * {@link FleetLaunchEnvironment.mcpTokenFor} DOES answer a route — only the one a RUNNING ferret asks about itself
 * (`POST /v1/sessions/:sessionId/mcp/token`, docs/mcp-oauth.md). It hands that ferret the one MCP sign-in token its
 * own launch already put in its environment (the documented GAP in `lib/mcp-inventory/project-sign-in.ts`: an agent
 * can read its own environment), renewed — because a ferret that outlives a twelve-hour access token would otherwise
 * send a dead one for ever and `/mcp` cannot help, as it expands the same stale variable. It is the same boundary
 * extended in time: it names a variable this runtime or this folder's project already binds, returns that one value
 * and no other secret, and the route refuses every caller but the ferret itself.
 *
 * ## Why the manifest and not the configuration
 *
 * The manifest is the record a start already reads, and it is regenerated by the same apply that
 * writes the wrappers — so it cannot describe an account differently from the wrapper that will run.
 * Reading the fleet CONFIGURATION here instead would make every session start depend on that document
 * parsing, and a host whose configuration file has a typo in it has perfectly good wrappers.
 *
 * ## What it costs when nobody uses a profile
 *
 * Nothing. An account that binds no secret answers `{}` without the store ever being opened, so the
 * overwhelming case — a fleet authenticated by ordinary logins — pays one lookup in a list it already
 * had. That is deliberate: a fresh account has to work with no profile at all.
 */

import { type FleetManifestAccount, resolveSecretEnvironment, wrapperNameOf } from '@ferretry/fleet';
import { parseMcpProjectSubject, type SecretName, secretReferencesIn } from '@ferretry/protocol';
import type { FerretMcpToken } from '../mcp-inventory/project-sign-in.ts';

/**
 * The extra environment one account's launch is entitled to, keyed by the executable it runs.
 *
 * A PORT, so the two launch paths depend on the decision rather than on the store. `wrapper` is the
 * absolute published path a session record carries; the name is derived from it the one sanctioned
 * way, so an account is never located by a string somebody assembled.
 */
export interface AccountLaunchEnvironment {
  /**
   * Empty when this executable is not a published account, binds no secret, and — given the folder the
   * pane starts in — that folder's project has signed in to none of its own MCP servers.
   */
  forWrapper(wrapper: string, cwd?: string): Promise<Readonly<Record<string, string>>>;
}

/**
 * The variables a PROJECT's signed-in MCP servers need in one launch, after their local-scope entries are
 * written (`lib/mcp-inventory/project-sign-in.ts`). Raises only for a fault, never for "nothing to do".
 */
export interface ProjectLaunchEnvironment {
  forLaunch(agent: string, cwd: string): Promise<Readonly<Record<string, string>>>;
  /** The token one signed-in project server is launched with, renewed, without writing anything. */
  token(agent: string, cwd: string, variable: string): Promise<FerretMcpToken>;
}

/** The published accounts, as the daemon's existing inventory already answers them. */
export interface LaunchAccountInventory {
  accounts(): Promise<readonly FleetManifestAccount[]>;
}

/** The opening half of the secret store. Structural, so the vault is passed rather than reached for. */
export interface LaunchSecretValues {
  values(): Promise<ReadonlyMap<SecretName, string>>;
}

/**
 * A chance to make the secrets a launch is about to resolve current first — an MCP sign-in whose access
 * token is about to expire (`docs/mcp-oauth.md`). It must never throw: a launch is not refused for it.
 */
export interface LaunchSecretRenewal {
  refreshForLaunch(names: readonly SecretName[]): Promise<void>;
  /** The sign-in that filed this access secret, when its refresh was rejected so only the person can mend it. */
  signInRequired?(name: SecretName): Promise<string | undefined>;
}

/**
 * Resolves one account's profile-bound environment for a launch.
 *
 * An account this daemon does not publish answers `{}` rather than refusing. A session may legally
 * run an executable that is not a fleet account — the authorization boundary decides that, and it is
 * not this module's question — and refusing here would turn "I have no opinion" into "you may not
 * start", which is a different answer given by the wrong component.
 *
 * A MISSING SECRET REFUSES THE LAUNCH, and that is the whole design: `resolveSecretEnvironment` raises
 * naming every secret the store does not hold, so the failure arrives at the start, on this machine,
 * naming the thing to fix. The alternative is an empty credential and a 401 from a remote service
 * twenty minutes later with nothing to point at.
 *
 * A DAMAGED STORE ALSO REFUSES, for the same reason it refuses a redaction: a vault that cannot be
 * opened is not a vault with nothing in it, and launching an account as though its profile were empty
 * would silently authenticate it as somebody else — or as nobody.
 */
export class FleetLaunchEnvironment implements AccountLaunchEnvironment {
  constructor(
    private readonly inventory: LaunchAccountInventory,
    private readonly secrets: LaunchSecretValues,
    private readonly renewal?: LaunchSecretRenewal,
    private readonly project?: ProjectLaunchEnvironment,
  ) {}

  async forWrapper(wrapper: string, cwd?: string): Promise<Readonly<Record<string, string>>> {
    const [own, project] = await Promise.all([
      this.#account(wrapper),
      cwd === undefined || this.project === undefined ? {} : this.project.forLaunch(wrapper, cwd),
    ]);
    // The profile's own bindings win a same-named variable: a project server's is derived, theirs is chosen.
    return { ...project, ...own };
  }

  /**
   * The current token behind one MCP sign-in variable this ferret was launched with — the account's own binding
   * (a component signed in to from Ferretry), else the folder's project server — renewed first, with nothing
   * written and no other secret read out. See the module doc for why this one method may answer a route.
   *
   * `unknown` when neither binds that variable; `needs-sign-in` when the sign-in was rejected or holds no token.
   */
  async mcpTokenFor(wrapper: string, cwd: string, variable: string): Promise<FerretMcpToken> {
    const bound = (await this.#boundSecretEnv(wrapper))[variable];
    if (bound === undefined) return (await this.project?.token(wrapper, cwd, variable)) ?? { kind: 'unknown' };
    const names = secretReferencesIn(bound);
    await this.renewal?.refreshForLaunch(names);
    const server = await this.#signInRequired(names);
    if (server !== undefined) return { kind: 'needs-sign-in', server: componentLabel(server) };
    const values = await this.secrets.values();
    const token = names.length === 1 ? values.get(names[0] as SecretName) : undefined;
    return token === undefined ? { kind: 'needs-sign-in', server: variableLabel(variable) } : { kind: 'token', token };
  }

  async #signInRequired(names: readonly SecretName[]): Promise<string | undefined> {
    for (const name of names) {
      const component = await this.renewal?.signInRequired?.(name);
      if (component !== undefined) return component;
    }
    return undefined;
  }

  async #boundSecretEnv(wrapper: string): Promise<Readonly<Record<string, string>>> {
    const name = wrapperNameOf(wrapper);
    const account = (await this.inventory.accounts()).find(
      published => wrapperNameOf(published.wrapper) === name || published.wrapper === wrapper,
    );
    return account?.secretEnv ?? {};
  }

  async #account(wrapper: string): Promise<Readonly<Record<string, string>>> {
    const name = wrapperNameOf(wrapper);
    const account = (await this.inventory.accounts()).find(
      published => wrapperNameOf(published.wrapper) === name || published.wrapper === wrapper,
    );
    if (account === undefined || Object.keys(account.secretEnv).length === 0) return {};
    // Opened only now, and only for an account that declared it needs something. A fleet nobody
    // gave a profile to never touches the store at all.
    // Renewal on USE: the only moment an MCP token is refreshed is the moment a launch needs it.
    await this.renewal?.refreshForLaunch([...new Set(Object.values(account.secretEnv).flatMap(secretReferencesIn))]);
    return resolveSecretEnvironment({ id: account.id, env: account.secretEnv }, await this.secrets.values());
  }
}

/**
 * The environment a pane is launched with: what the account's profile supplies, then what the session
 * itself owns.
 *
 * THE SESSION WINS. Its own document carries the credential a task board issued it and any variable a
 * grant delivered, and those name that one session; a profile is shared by every account that lists
 * it. A profile able to overwrite them would let one shared document take a teammate's board
 * capability away from it — so the precedence runs the only direction that cannot do that, and the
 * session id the launcher derives afterwards is still written last.
 *
 * NEITHER MAY SET `HOME`. A runtime keeps the person's real home on macOS and Linux alike: that is
 * where their own Claude and Codex logins are found, and where Claude finds the macOS keychain
 * (docs/design/account-model.md §8.1.1). The config directory the wrapper exports is what keeps a
 * runtime separate, and the wrapper never sets `HOME` — so a value handed to the pane here would be
 * the only one, and it would sign the runtime out. The pane inherits the daemon's own instead.
 */
export function launchEnvironment(
  account: Readonly<Record<string, string>>,
  session: Readonly<Record<string, string>>,
): Readonly<Record<string, string>> {
  const { HOME: _accountHome, ...fromAccount } = account;
  const { HOME: _sessionHome, ...fromSession } = session;
  return { ...fromAccount, ...fromSession };
}

/** A sign-in's component name, as a person knows the server: a project server's subject is its name and a folder. */
const componentLabel = (component: string): string => parseMcpProjectSubject(component)?.name ?? component;

/** The server a sign-in variable belongs to, as far as the variable says: `FY_MCP_<NAME>_<16 hex>_TOKEN`. */
const variableLabel = (variable: string): string =>
  /^FY_MCP_(?:([A-Z0-9_]+?)_)?[0-9A-F]{16}_TOKEN$/u.exec(variable)?.[1]?.toLowerCase().replaceAll('_', '-') ?? variable;
