/**
 * `fyd` — the daemon entry (§8: at most 150 lines, names no subsystem; `host-files`). Everything a plugin adds comes
 * from the generated registry; everything IO from the kernel's adapters.
 */
import { appendFileSync, mkdirSync } from 'node:fs';
import { chmod, rm, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import type { DaemonImplementation } from '../manifest/implement.ts';
import { bootHost } from './host.ts';
import { listenLocal } from './listener.ts';
import { fileLogSink, realAdapters } from './wiring.ts';

interface GeneratedRegistry {
  readonly daemonImplementations: readonly DaemonImplementation[];
  readonly contractHashes?: Readonly<Record<string, { readonly effective: string }>>;
}

/** Written by `scripts/gen/registries.ts` (git-ignored, regenerated by install, build, test and typecheck). */
const REGISTRY = '../src/generated/plugins.ts';
const VERSION = '5.0.0';
const DEFAULT_PORT = 7457;
/** The binary name is single-sourced from `packages/cli/package.json` `bin`; the release build replaces this. */
const BINARY = process.env.FY_BINARY_NAME ?? 'fy';

function argument(name: string): string | undefined {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

async function main(): Promise<number> {
  const home = (process.env.FY_HOME ?? `${homedir()}/.ferretry`).replace(/\/+$/, '');
  const port = Number(argument('--port') ?? process.env.FY_PORT ?? DEFAULT_PORT);
  if (!Number.isInteger(port) || port < 0 || port > 65_535) {
    process.stderr.write(`fyd: --port ${port} is not a port number.\n`);
    return 64;
  }
  mkdirSync(`${home}/logs`, { recursive: true, mode: 0o700 });
  const sink = fileLogSink(line => appendFileSync(`${home}/logs/fyd.log`, line, { mode: 0o600 }));
  const registry = (await import(REGISTRY)) as GeneratedRegistry;
  const outcome = await bootHost({
    home,
    version: VERSION,
    implementations: registry.daemonImplementations,
    adapters: realAdapters(home, sink, { binary: BINARY, childEnv: { PATH: process.env.PATH ?? '/usr/bin:/bin', HOME: homedir() } }),
    contractHash: id => registry.contractHashes?.[id]?.effective ?? 'unhashed',
    pid: process.pid,
    listen: async host =>
      await listenLocal(host, {
        home,
        port,
        pid: process.pid,
        version: VERSION,
        write: (path, text) => writeFile(path, text, { mode: 0o600 }),
        chmod: (path, mode) => chmod(path, mode),
        remove: path => rm(path, { force: true }),
      }),
  });
  if (outcome.kind === 'refused') {
    process.stderr.write(`${outcome.sentence}\n`);
    return 78;
  }
  const { host } = outcome;
  for (const line of await host.doctor()) if (line.state === 'fail') process.stderr.write(`fyd: ${line.detail}\n`);
  process.stderr.write(`fyd ${VERSION} ready (${host.identity.fingerprint.slice(0, 12)})\n`);
  const stopped = new Promise<void>(resolve => {
    const stop = (): void => {
      void host.stop().then(resolve);
    };
    process.once('SIGTERM', stop);
    process.once('SIGINT', stop);
  });
  await stopped;
  return 0;
}

process.exitCode = await main();
