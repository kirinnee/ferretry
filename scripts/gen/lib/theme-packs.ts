/**
 * Theme packs: a style, a palette and a font are each one folder under `packages/app/src/theme/packs/<kind>/<id>/`
 * (`palette.ts`, `style.ts` + `style.css`, `font.ts` + its `.woff2` files), and this file turns that folder tree into the
 * two git-ignored files the app reads, so a pack is added by adding a folder and no list is edited:
 *
 *   packages/app/src/generated/theme-packs.ts    `STYLE_PACKS`, `PALETTE_PACKS`, `FONT_PACKS` (sorted by `order`, then id)
 *                                                and the `as const` id lists, so app code keeps exact union types
 *   packages/app/src/generated/theme-packs.css   the `@import` of every `style.css`, the `@font-face` of every font, every
 *                                                palette's data as selector blocks, and the default palette's dark block as
 *                                                the unqualified dark baseline
 *
 * Every pack is parsed with the app's own schema (`pack-contract.ts`). A pack that does not parse, a folder that is not its
 * id, a duplicate id, a second default, a missing font or file fails GENERATION naming the pack path, so a broken pack
 * never ships. No packs is valid: empty arrays and an empty stylesheet.
 *
 * The loader reads pack files with a synchronous `require` so `generateGlobal` stays synchronous, and only `zod` (a runtime
 * dependency) and Bun are needed, because the generator also runs in the Nix build without devDependencies.
 */
import { existsSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { FontPackSchema, PalettePackSchema, StylePackSchema } from '../../../packages/app/src/theme/pack-contract.ts';
import { entryList } from './entry-lines.ts';
import { ident, importPath } from './folder-registry.ts';

export const THEME_PACKS_DIR = 'packages/app/src/theme/packs';
export const THEME_PACKS_TS = 'packages/app/src/generated/theme-packs.ts';
export const THEME_PACKS_CSS = 'packages/app/src/generated/theme-packs.css';

const HEADER =
  '// Generated by scripts/gen/registries.ts. Do not edit; regenerate with `bun scripts/gen/registries.ts`.\n';
const CSS_HEADER =
  '/* Generated by scripts/gen/registries.ts. Do not edit; regenerate with `bun scripts/gen/registries.ts`. */\n';

/** The subset every bundled font file is cut to (the `latin` range). */
const LATIN_RANGE =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';

type PackKind = 'style' | 'palette' | 'font';
type PalettePack = ReturnType<typeof PalettePackSchema.parse>;
type StylePack = ReturnType<typeof StylePackSchema.parse>;
type FontPack = ReturnType<typeof FontPackSchema.parse>;

/** Code-unit order, so no locale changes it. */
const byName = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

interface Loaded<T extends { readonly id: string }> {
  /** Pack file, relative to the root (`packages/app/src/theme/packs/palette/ink/palette.ts`). */
  readonly rel: string;
  readonly abs: string;
  readonly pack: T;
}

type Parser<T> = {
  safeParse(
    input: unknown,
  ):
    | { success: true; data: T }
    | { success: false; error: { issues: readonly { path: readonly PropertyKey[]; message: string }[] } };
};

/** Every pack of one kind, in folder-name order, plus what is wrong with any of them. */
function loadKind<T extends { readonly id: string }>(
  root: string,
  kind: PackKind,
  schema: Parser<T>,
  problems: string[],
): Loaded<T>[] {
  const kindDir = join(root, THEME_PACKS_DIR, kind);
  if (!existsSync(kindDir)) return [];
  const require = createRequire(import.meta.url);
  const loaded: Loaded<T>[] = [];
  const folders = readdirSync(kindDir, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort(byName);
  for (const folder of folders) {
    const rel = `${THEME_PACKS_DIR}/${kind}/${folder}/${kind}.ts`;
    const abs = join(root, rel);
    if (!existsSync(abs)) {
      problems.push(`${rel}: missing (a ${kind} pack is a folder with a ${kind}.ts)`);
      continue;
    }
    let data: unknown;
    try {
      delete require.cache[abs];
      data = (require(abs) as { default?: unknown }).default;
    } catch (error) {
      problems.push(`${rel}: does not load: ${error instanceof Error ? error.message : String(error)}`);
      continue;
    }
    const parsed = schema.safeParse(data);
    if (!parsed.success) {
      for (const issue of parsed.error.issues)
        problems.push(`${rel}: ${issue.path.map(String).join('.') || '(pack)'}: ${issue.message}`);
      continue;
    }
    if (parsed.data.id !== folder)
      problems.push(`${rel}: id "${parsed.data.id}" must equal its folder name "${folder}"`);
    loaded.push({ rel, abs, pack: parsed.data });
  }
  return loaded;
}

/** Unique ids; exactly one `default` once the kind has any pack. */
function checkIds(
  kind: PackKind,
  packs: readonly Loaded<{ readonly id: string; readonly default?: true }>[],
  problems: string[],
): void {
  const seen = new Map<string, string>();
  for (const { rel, pack } of packs) {
    const first = seen.get(pack.id);
    if (first !== undefined) problems.push(`${rel}: duplicate ${kind} id "${pack.id}" (also ${first})`);
    else seen.set(pack.id, rel);
  }
  const defaults = packs.filter(entry => entry.pack.default === true);
  if (kind !== 'font' && packs.length > 0 && defaults.length !== 1)
    problems.push(
      `${THEME_PACKS_DIR}/${kind}: exactly one ${kind} pack must be \`default: true\`, found ${defaults.length}${defaults.length > 1 ? ` (${defaults.map(entry => entry.rel).join(', ')})` : ''}`,
    );
}

const orderThenId = <T extends { readonly id: string; readonly order: number }>(a: Loaded<T>, b: Loaded<T>): number =>
  a.pack.order - b.pack.order || byName(a.pack.id, b.pack.id);

const selectors = (palette: string, mode?: 'light' | 'dark'): string => {
  const mine = `[data-palette='${palette}']${mode === undefined ? '' : `[data-mode='${mode}']`}`;
  return `:root${mine},\n[data-swatch]${mine}`;
};

const glowCss = (glow: { w: number; h: number; x: number; y: number; colour: string; fade: number }): string =>
  `radial-gradient(${glow.w}% ${glow.h}% at ${glow.x}% ${glow.y}%, ${glow.colour}, transparent ${glow.fade}%)`;

/** One block of declarations: the palette's tokens, then its mesh as `--surface-mesh`. */
function declarations(
  tokens: Readonly<Record<string, string>>,
  glows: readonly Parameters<typeof glowCss>[0][],
): string[] {
  const lines = Object.entries(tokens).map(([name, value]) => `  --${name}: ${value};`);
  if (glows.length > 0) lines.push(`  --surface-mesh:\n${glows.map(glow => `    ${glowCss(glow)}`).join(',\n')};`);
  return lines;
}

const block = (selector: string, lines: readonly string[]): string => `${selector} {\n${lines.join('\n')}\n}`;

function paletteCss(palette: PalettePack): string[] {
  return (['light', 'dark'] as const).map(mode =>
    block(selectors(palette.id, mode), declarations(palette[mode], palette.mesh?.[mode] ?? [])),
  );
}

/** The CSS a font pack declares: one `@font-face` per face. */
function fontCss(font: FontPack, folderRel: string, out: string, root: string): string[] {
  return font.faces.map(face =>
    [
      '@font-face {',
      `  font-family: '${font.family}';`,
      `  font-style: ${face.style};`,
      `  font-weight: ${face.weight};`,
      '  font-display: swap;',
      `  src: url('${importPath(out, join(root, folderRel, face.file))}') format('woff2');`,
      `  unicode-range: ${LATIN_RANGE};`,
      '}',
    ].join('\n'),
  );
}

/**
 * `theme-packs.ts` and `theme-packs.css` of the pack tree under `root`, keyed by root-relative path. Throws one error naming
 * every problem (pack path first) when any pack is not valid.
 */
export function themePackFiles(root: string): ReadonlyMap<string, string> {
  const problems: string[] = [];
  const palettes = loadKind<PalettePack>(root, 'palette', PalettePackSchema, problems);
  const styles = loadKind<StylePack>(root, 'style', StylePackSchema, problems);
  const fonts = loadKind<FontPack>(root, 'font', FontPackSchema, problems);
  checkIds('palette', palettes, problems);
  checkIds('style', styles, problems);
  checkIds('font', fonts, problems);

  const paletteIds = new Set(palettes.map(entry => entry.pack.id));
  const fontIds = new Set(fonts.map(entry => entry.pack.id));
  for (const { rel, pack } of palettes)
    for (const mode of ['light', 'dark'] as const)
      if (pack.mesh !== undefined && pack.mesh[mode].length > 0 && 'surface-mesh' in pack[mode])
        problems.push(`${rel}: ${mode}.surface-mesh: set by \`mesh\` already; name one of them`);
  for (const { rel, pack } of styles) {
    if (!paletteIds.has(pack.defaultPalette))
      problems.push(`${rel}: defaultPalette "${pack.defaultPalette}" is not a palette pack`);
    for (const id of [...pack.fonts.text, ...pack.fonts.code])
      if (!fontIds.has(id)) problems.push(`${rel}: fonts: "${id}" is not a font pack`);
  }
  for (const { rel, abs, pack } of fonts)
    for (const face of pack.faces)
      if (!existsSync(join(abs, '..', face.file))) problems.push(`${rel}: faces: ${face.file} does not exist`);
  for (const { rel, abs } of styles)
    if (!existsSync(join(abs, '..', 'style.css'))) problems.push(`${rel}: style.css does not exist beside it`);
  if (problems.length > 0)
    throw new Error(`theme packs are not valid:\n${problems.map(line => `  - ${line}`).join('\n')}`);

  const tsOut = join(root, THEME_PACKS_TS);
  const cssOut = join(root, THEME_PACKS_CSS);
  const sorted = {
    palette: [...palettes].sort(orderThenId),
    style: [...styles].sort(orderThenId),
    font: [...fonts].sort((a, b) => byName(a.pack.id, b.pack.id)),
  } as const;
  const list = (kind: PackKind, constant: string, doc: string): string[] => {
    const entries = sorted[kind];
    return [
      ...entryList(
        `/** ${doc} */\nexport const ${constant} = [`,
        entries.map(entry => ident(kind, entry.pack.id)),
        '] as const;',
      ),
      ...entryList(
        `export const ${constant.replace('_PACKS', '_IDS')} = [`,
        entries.map(entry => JSON.stringify(entry.pack.id)),
        '] as const;',
      ),
      '',
    ];
  };
  const ts = [
    HEADER,
    ...(['palette', 'style', 'font'] as const).flatMap(kind =>
      sorted[kind].map(entry => `import ${ident(kind, entry.pack.id)} from '${importPath(tsOut, entry.abs)}';`),
    ),
    '',
    ...list('style', 'STYLE_PACKS', 'Every style pack (theme/packs/style/<id>/style.ts), by `order` then id.'),
    ...list(
      'palette',
      'PALETTE_PACKS',
      'Every palette pack (theme/packs/palette/<id>/palette.ts), by `order` then id.',
    ),
    ...list('font', 'FONT_PACKS', 'Every font pack (theme/packs/font/<id>/font.ts), by id.'),
  ];

  const defaultPalette = sorted.palette.find(entry => entry.pack.default === true)?.pack;
  const imports = sorted.style.map(entry => `@import '${importPath(cssOut, join(entry.abs, '..', 'style.css'))}';`);
  const blocks = [
    ...sorted.font.flatMap(entry => fontCss(entry.pack, entry.rel.slice(0, entry.rel.lastIndexOf('/')), cssOut, root)),
    // An id with no pack matches no palette selector; this dark baseline keeps the default palette's dark look in dark mode.
    ...(defaultPalette === undefined
      ? []
      : [
          block(
            ":root[data-mode='dark'],\n[data-swatch][data-mode='dark']",
            declarations(defaultPalette.dark, defaultPalette.mesh?.dark ?? []),
          ),
        ]),
    ...sorted.palette.flatMap(entry => paletteCss(entry.pack)),
  ];
  // `@import` must come first in a stylesheet: styles, then fonts, then palettes. A pack's selectors never overlap another's.
  const css = [
    CSS_HEADER,
    ...(imports.length > 0 ? [imports.join('\n'), ''] : []),
    ...blocks.flatMap(b => [b, '']),
  ].join('\n');
  return new Map([
    [THEME_PACKS_TS, ts.join('\n')],
    [THEME_PACKS_CSS, css],
  ]);
}
