/**
 * Generation is OPTIONAL: a feature may add its own line to a registry by hand. So `--check` (`registries-fresh`) accepts a
 * hand-added line that is where the generator would put it, and refuses one that is not with a fixed sentence that says
 * where the line goes. These tests pin both on a real feature registry, and the sentence-maker on its own.
 */
import { afterAll, describe, expect, test } from 'bun:test';
import { explainStale } from '../lib/entry-lines.ts';
import { type Fixture, fixture, skeletonHalf } from './fixture.ts';
import { buildModel, featureRegistries, featureRegistryPath, staleFiles } from '../registries.ts';

const made: Fixture[] = [];
afterAll(() => {
  for (const f of made) f.dispose();
});
const PATH = featureRegistryPath('packages/plugins/alpha');
const feature = 'export default { id: "x", register: () => undefined };\n';

/** A package with three features on disk and the registry a person committed, then the generator's view of it. */
async function world(names: readonly string[]): Promise<{ f: Fixture; fresh: ReadonlyMap<string, string> }> {
  const f = fixture([
    {
      id: 'alpha',
      daemon: skeletonHalf('Daemon'),
      app: skeletonHalf('App'),
      cli: skeletonHalf('Cli'),
      files: Object.fromEntries(names.map(name => [`daemon/features/${name}.feature.ts`, feature])),
    },
  ]);
  made.push(f);
  return { f, fresh: featureRegistries(await buildModel(f.root, false)) };
}

const registry = (names: readonly string[]): string =>
  [
    '// Generated by scripts/gen/registries.ts. Do not edit; regenerate with `bun scripts/gen/registries.ts`.',
    '',
    ...names.map(name => `import feature_${name} from '../features/${name}.feature.ts';`),
    '',
    "/** Every feature of this package's daemon half, by file name (daemon/features/*.feature.ts). */",
    'export default [',
    ...names.map(name => `  feature_${name},`),
    '] as const;',
    '',
  ].join('\n');

describe('--check with a hand-edited registry', () => {
  test('the generator writes exactly the shape a person writes by hand', async () => {
    const { fresh } = await world(['alpha', 'bravo', 'delta']);
    expect(fresh.get(PATH)).toBe(registry(['alpha', 'bravo', 'delta']));
  });

  test('a line added by hand where the generator would put it passes, with no regeneration', async () => {
    const { f, fresh } = await world(['alpha', 'bravo', 'charlie', 'delta']);
    // The person added `charlie.feature.ts` and its two lines, in sorted place, and ran no generator.
    f.write(PATH, registry(['alpha', 'bravo', 'charlie', 'delta']));
    expect(staleFiles(f.root, fresh, false)).toEqual([]);
  });

  test('a line added by hand in the wrong place fails, and the sentence says where it goes', async () => {
    const { f, fresh } = await world(['alpha', 'bravo', 'charlie', 'delta']);
    f.write(PATH, registry(['alpha', 'charlie', 'bravo', 'delta']));
    expect(staleFiles(f.root, fresh, false)).toEqual([PATH]);
    const disk = registry(['alpha', 'charlie', 'bravo', 'delta']);
    expect(explainStale(disk, fresh.get(PATH) ?? '')).toEqual([
      "`import feature_bravo from '../features/bravo.feature.ts';` is out of order: it goes after `import feature_alpha from '../features/alpha.feature.ts';`",
    ]);
  });

  test('a hand-added line for a file that is not there, and a file with no line, each say so', async () => {
    const { fresh } = await world(['alpha', 'bravo']);
    const want = fresh.get(PATH) ?? '';
    expect(explainStale(registry(['alpha', 'bravo', 'ghost']), want)).toEqual([
      "`import feature_ghost from '../features/ghost.feature.ts';` is not an entry the generator would write",
      '`feature_ghost,` is not an entry the generator would write',
    ]);
    expect(explainStale(registry(['alpha']), want)).toEqual([
      "`import feature_bravo from '../features/bravo.feature.ts';` is missing: it goes after `import feature_alpha from '../features/alpha.feature.ts';`",
      '`feature_bravo,` is missing: it goes after `feature_alpha,`',
    ]);
  });

  test('equal texts have nothing to say', () => {
    expect(explainStale('a\nb\n', 'a\nb\n')).toEqual([]);
  });
});
