/** The generated client binary name equals the `bin` key of packages/cli/package.json, so `rename.sh --bin` moves it. */
import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { clientBinary } from '../registries.ts';
import type { Model } from '../registries.ts';

const root = join(import.meta.dir, '..', '..', '..');

describe('generated client binary', () => {
  test('CLIENT_BINARY is the first bin key of packages/cli/package.json, not a literal', () => {
    const cli = JSON.parse(readFileSync(join(root, 'packages/cli/package.json'), 'utf8')) as {
      bin: Record<string, string>;
    };
    const source = clientBinary({ ws: { root } } as unknown as Model);
    expect(source).toContain(`export const CLIENT_BINARY = ${JSON.stringify(Object.keys(cli.bin)[0])};`);
    expect(source.startsWith('// Generated by scripts/gen/registries.ts.')).toBe(true);
  });
});
