/**
 * The registry generator (§7.5). Finds packages through the root `workspaces` globs, checks the graph, resolves
 * start and hook order, hashes every contract (§9.6), and writes:
 *
 *   packages/core/kernel/src/generated/plugins.ts   daemon halves in start order + contract hashes
 *   packages/core/kernel/src/generated/glossary.ts  every manifest's words
 *   packages/cli/src/generated/commands.ts          CLI halves + contract hashes
 *   packages/app/src/generated/surfaces.ts          app halves + contract hashes
 *   generated/hooks.md                              offers, takers and their order
 *   generated/contract-hashes.json                  canonical + effective hash per package (the release compare)
 *
 * With `--package <id>` it instead writes `generated/package/<id>/plugins.ts`: that package's three halves plus the
 * contract fakes (`contract/testing`) of everything it consumes and nothing else (§3.9), so one port can go green
 * while the rest are skeletons.
 *
 * Imports are RELATIVE paths: the workspace links with Bun's isolated linker, so the kernel cannot resolve a plugin
 * package by name. Generated files are git-ignored. `--check` writes nothing and exits 1 when a file on disk differs
 * from a fresh generation (`registries-fresh`).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { buildGraph, hookOrder } from './lib/graph.ts';
import type { StartGraph } from './lib/graph.ts';
import {
  type ContractHashes,
  canonicalJson,
  consumedBy,
  effectiveHashes,
  loadToJsonSchema,
  memberSurfaceOf,
  sha256,
  surfaceOf,
} from './lib/hashes.ts';
import { type ImportEdge, importsOf, scannedImportsOf } from './lib/imports.ts';
import { readPendingApps } from './lib/pending-apps.ts';
import {
  HALVES,
  type LoadedSubsystem,
  type Workspace,
  contractPath,
  halfPath,
  loadManifests,
  loadWorkspace,
  sourceFiles,
} from './lib/workspace.ts';

export const GENERATED = {
  plugins: 'packages/core/kernel/src/generated/plugins.ts',
  glossary: 'packages/core/kernel/src/generated/glossary.ts',
  commands: 'packages/cli/src/generated/commands.ts',
  surfaces: 'packages/app/src/generated/surfaces.ts',
  hooks: 'generated/hooks.md',
  hashes: 'generated/contract-hashes.json',
} as const;

export const packageRegistryPath = (id: string): string => `generated/package/${id}/plugins.ts`;

const HEADER =
  '// Generated by scripts/gen/registries.ts. Do not edit; regenerate with `bun scripts/gen/registries.ts`.\n';

export interface Model {
  readonly ws: Workspace;
  readonly loaded: readonly LoadedSubsystem[];
  readonly failures: readonly string[];
  readonly graph: StartGraph;
  readonly edges: readonly ImportEdge[];
  readonly consumed: ReadonlyMap<string, ReadonlySet<string>>;
  readonly hashes: ReadonlyMap<string, ContractHashes>;
}

/**
 * Everything the generator and the checks share: manifests, graph, import edges, hashes. The hashes always come from
 * the scanned edges, so a generation and a check agree. `precise` (the default) also parses every file with
 * oxc-parser for `model.edges`, which only the checks read; the generator passes `false` because oxc-parser is a
 * devDependency the production install (the Nix build) does not have.
 */
export async function buildModel(root: string, precise = true): Promise<Model> {
  const ws = loadWorkspace(root);
  const { loaded, failures } = await loadManifests(ws);
  const graph = buildGraph(loaded);
  const scanned: ImportEdge[] = [];
  const edges: ImportEdge[] = [];
  const parseFailures: string[] = [];
  for (const pkg of ws.packages)
    for (const file of sourceFiles(pkg)) {
      if (file.includes(`${sep}generated${sep}`)) continue;
      try {
        scanned.push(...scannedImportsOf(ws, file));
        if (precise) edges.push(...importsOf(ws, file));
      } catch (error) {
        parseFailures.push(error instanceof Error ? error.message : String(error));
      }
    }
  const consumed = consumedBy(graph, scanned);
  const toJsonSchema = await loadToJsonSchema();
  const canonical = new Map<string, string>();
  const member = new Map<string, string>();
  const hashFailures: string[] = [];
  for (const subsystem of loaded) {
    try {
      const surface = memberSurfaceOf(subsystem, toJsonSchema);
      if (surface !== undefined) member.set(subsystem.id, sha256(canonicalJson(surface)));
      canonical.set(subsystem.id, sha256(canonicalJson(await surfaceOf(ws, subsystem, toJsonSchema))));
    } catch (error) {
      // A contract that does not load has no hash anyone can match: its clients stay paused (§9.6).
      const message = error instanceof Error ? error.message : String(error);
      hashFailures.push(`${subsystem.pkg.rel}: contract failed to load: ${message}`);
      canonical.set(subsystem.id, sha256(`unloadable\n${message}`));
    }
  }
  return {
    ws,
    loaded,
    failures: [...failures, ...parseFailures, ...hashFailures],
    graph,
    edges: precise ? edges : scanned,
    consumed,
    hashes: effectiveHashes(canonical, consumed, member),
  };
}

function importPath(fromFile: string, target: string): string {
  const rel = relative(dirname(fromFile), target).split(sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

const ident = (prefix: string, id: string): string => `${prefix}_${id.replace(/[^a-zA-Z0-9]/g, '_')}`;

function hashesLiteral(model: Model, ids: readonly string[]): string {
  const lines = ids
    .filter(id => model.hashes.has(id))
    .map(id => {
      const hash = model.hashes.get(id) as ContractHashes;
      const member = hash.member === undefined ? '' : `, member: ${JSON.stringify(hash.member)}`;
      return `  ${JSON.stringify(id)}: { canonical: ${JSON.stringify(hash.canonical)}, effective: ${JSON.stringify(hash.effective)}${member} },`;
    });
  return `{\n${lines.join('\n')}\n}`;
}

function startOrder(model: Model): readonly string[] {
  return model.graph.order ?? model.graph.ids;
}

function halfRegistry(
  model: Model,
  outRel: string,
  half: 'daemon' | 'app' | 'cli',
  typeName: string,
  exportName: string,
): string {
  const out = join(model.ws.root, outRel);
  const kernel = model.ws.byId('kernel');
  const sdk = kernel === undefined ? undefined : join(kernel.dir, 'manifest', 'index.ts');
  const imports: string[] = [];
  const names: string[] = [];
  for (const id of startOrder(model)) {
    const pkg = model.ws.byId(id);
    const file = pkg === undefined ? undefined : halfPath(pkg, half);
    if (file === undefined) continue;
    const name = ident(half, id);
    imports.push(`import ${name} from '${importPath(out, file)}';`);
    names.push(name);
  }
  const generation = sha256(
    startOrder(model)
      .map(id => `${id}=${model.hashes.get(id)?.effective ?? ''}`)
      .join('\n'),
  );
  return [
    HEADER,
    sdk === undefined ? '' : `import type { ${typeName} } from '${importPath(out, sdk)}';`,
    ...imports,
    '',
    `/** Every ${half} half, in start order (§7.6). */`,
    `export const ${exportName}: readonly ${typeName}<any>[] = [${names.join(', ')}];`,
    '',
    '/** Start order: needs and taken hooks first, then kernel, core, and id (§7.6). */',
    `export const startOrder: readonly string[] = ${JSON.stringify(startOrder(model))};`,
    '',
    '/** Canonical and effective contract hash per package, and the member-surface hash where it has member routes (§9.6). */',
    `export const contractHashes: Readonly<Record<string, { readonly canonical: string; readonly effective: string; readonly member?: string }>> = ${hashesLiteral(model, startOrder(model))};`,
    '',
    '/** One value for the whole build: changes when any effective hash or the start order changes. */',
    `export const generation = ${JSON.stringify(generation)};`,
    '',
  ].join('\n');
}

/**
 * `packages/cli/src/generated/commands.ts` in the `fy` shell's shape (`packages/cli/src/lib/registry.ts`):
 * `registry: CommandRegistry = { plugins: [{ id, manifest, contract, load() }] }`. Manifests are imported statically;
 * each CLI half loads lazily, so a verb loads only the plugin it runs.
 */
function commandsRegistry(model: Model): string {
  const out = join(model.ws.root, GENERATED.commands);
  const imports: string[] = [];
  const entries: string[] = [];
  // The Kernel has no CLI half, but its routes and its effective hash belong to every client's guard (§9.6).
  const kernel = model.ws.byId('kernel');
  if (kernel?.manifestPath === undefined) throw new Error('the kernel package declares no manifest');
  imports.push(`import manifest_kernel from '${importPath(out, kernel.manifestPath)}';`);
  const kernelEntry = `  kernel: { manifest: manifest_kernel, contract: ${JSON.stringify(model.hashes.get('kernel')?.effective ?? 'unhashed')} },`;
  for (const id of startOrder(model)) {
    const pkg = model.ws.byId(id);
    const cli = pkg === undefined ? undefined : halfPath(pkg, 'cli');
    if (pkg?.manifestPath === undefined || cli === undefined) continue;
    const name = ident('manifest', id);
    imports.push(`import ${name} from '${importPath(out, pkg.manifestPath)}';`);
    entries.push(
      `    { id: ${JSON.stringify(id)}, manifest: ${name}, contract: ${JSON.stringify(model.hashes.get(id)?.effective ?? 'unhashed')}, load: async () => (await import('${importPath(out, cli)}')).default },`,
    );
  }
  return [
    HEADER,
    "import type { CommandRegistry } from '../lib/registry.ts';",
    ...imports,
    '',
    '/** Every subsystem with a CLI half, in start order (§7.5). */',
    `export const registry: CommandRegistry = {\n${kernelEntry}\n  plugins: [\n${entries.join('\n')}\n  ],\n};`,
    '',
  ].join('\n');
}

/**
 * `packages/app/src/generated/surfaces.ts` in the app shell's shape (`packages/app/src/surfaces/registry.ts`):
 * `generated: GeneratedSurfaces = { appVersion, surfaces: [{ id, title, core, contract, consumes, manifest, app? }] }`.
 * The kernel has no app half, so its entry carries no `app`.
 */
function surfacesRegistry(model: Model): string {
  const out = join(model.ws.root, GENERATED.surfaces);
  const pendingApps = readPendingApps(model.ws.root).halves;
  const imports: string[] = [];
  const entries: string[] = [];
  for (const id of startOrder(model)) {
    const pkg = model.ws.byId(id);
    if (pkg?.manifestPath === undefined) continue;
    const manifest = ident('manifest', id);
    imports.push(`import ${manifest} from '${importPath(out, pkg.manifestPath)}';`);
    const app = pendingApps.has(id) ? undefined : halfPath(pkg, 'app');
    const appName = ident('app', id);
    if (app !== undefined) imports.push(`import ${appName} from '${importPath(out, app)}';`);
    entries.push(
      `    { id: ${JSON.stringify(id)}, title: ${manifest}.title, core: ${manifest}.core, contract: ${JSON.stringify(model.hashes.get(id)?.effective ?? 'unhashed')}, consumes: ${JSON.stringify([...(model.consumed.get(id) ?? [])].sort())}, manifest: ${manifest}${app === undefined ? '' : `, app: ${appName}`} },`,
    );
  }
  const version =
    (JSON.parse(readFileSync(join(model.ws.root, 'package.json'), 'utf8')) as { version?: string }).version ?? '0.0.0';
  return [
    HEADER,
    "import type { GeneratedSurfaces } from '../surfaces/registry.ts';",
    ...imports,
    '',
    '/** Every subsystem, in start order, with its effective contract hash and what it consumes (§9.6). */',
    `export const generated: GeneratedSurfaces = {\n  appVersion: ${JSON.stringify(version)},\n  surfaces: [\n${entries.join('\n')}\n  ],\n};`,
    '',
  ].join('\n');
}

function glossary(model: Model): string {
  const words = model.loaded
    .flatMap(s => (s.manifest.words ?? []).map(word => ({ plugin: s.id, ...word })))
    .sort((a, b) => a.word.localeCompare(b.word) || a.plugin.localeCompare(b.plugin));
  return [
    HEADER,
    '/** Every word a manifest owns (§1.2), for `GET /v1/glossary`, `fy words` and the `glossary` check. */',
    'export interface GlossaryEntry {',
    '  readonly plugin: string;',
    '  readonly word: string;',
    '  readonly means: string;',
    '  readonly insteadOf?: readonly string[];',
    '}',
    '',
    `export const glossary: readonly GlossaryEntry[] = ${JSON.stringify(words, null, 2)};`,
    '',
  ].join('\n');
}

function hooksMarkdown(model: Model): string {
  const order = hookOrder(model.graph);
  const lines = [
    '<!-- Generated by scripts/gen/registries.ts. Do not edit. -->',
    '# Hooks',
    '',
    'Every hook a manifest offers, its mode, and its takers in invocation order (priority, then start order, then id).',
    '',
  ];
  for (const name of [...model.graph.hooks.keys()].sort()) {
    const hook = model.graph.hooks.get(name);
    if (hook === undefined) continue;
    const security =
      hook.mode === 'decide' && hook.securityPath
        ? ' · security path (core only)'
        : hook.mode === 'provide' && hook.takers !== undefined
          ? ` · takers: ${hook.takers.join(', ') || 'none'}`
          : '';
    lines.push(
      `## \`${name}\``,
      '',
      `${hook.mode} · offered by ${(model.graph.offerers.get(name) ?? []).join(', ')}${security}`,
      '',
    );
    const takers = order.get(name) ?? [];
    if (takers.length === 0) lines.push('No takers.', '');
    else {
      for (const taker of takers)
        lines.push(`1. ${taker.id}${taker.key === undefined ? '' : ` (key \`${taker.key}\`)`}`);
      lines.push('');
    }
  }
  lines.push('## Start order', '', (model.graph.order ?? []).join(' → ') || 'none: the graph has a cycle', '');
  return lines.join('\n');
}

function hashesJson(model: Model): string {
  const record: Record<string, ContractHashes> = {};
  for (const id of [...model.hashes.keys()].sort()) record[id] = model.hashes.get(id) as ContractHashes;
  return `${JSON.stringify({ format: 1, hashes: record }, null, 2)}\n`;
}

/** The global registries, keyed by root-relative path. */
export function generateGlobal(model: Model): ReadonlyMap<string, string> {
  return new Map([
    [
      GENERATED.plugins,
      halfRegistry(model, GENERATED.plugins, 'daemon', 'DaemonImplementation', 'daemonImplementations'),
    ],
    [GENERATED.glossary, glossary(model)],
    [GENERATED.commands, commandsRegistry(model)],
    [GENERATED.surfaces, surfacesRegistry(model)],
    [GENERATED.hooks, hooksMarkdown(model)],
    [GENERATED.hashes, hashesJson(model)],
  ]);
}

/** The package-scoped registry (§3.9): one package's halves plus the contract fakes of what it consumes. */
export function generatePackage(model: Model, id: string): ReadonlyMap<string, string> {
  const pkg = model.ws.byId(id);
  if (pkg === undefined) throw new Error(`no package with id "${id}"`);
  const outRel = packageRegistryPath(id);
  const out = join(model.ws.root, outRel);
  const lines = [HEADER];
  const halves: string[] = [];
  for (const half of HALVES) {
    const file = halfPath(pkg, half);
    if (file === undefined) continue;
    lines.push(`import ${half} from '${importPath(out, file)}';`);
    halves.push(half);
  }
  const consumed = [...(model.consumed.get(id) ?? [])].sort();
  const fakes: string[] = [];
  for (const other of consumed) {
    const otherPkg = model.ws.byId(other);
    const testing = otherPkg === undefined ? undefined : contractPath(otherPkg, true);
    if (testing === undefined) continue;
    const name = ident('testing', other);
    lines.push(`import * as ${name} from '${importPath(out, testing)}';`);
    fakes.push(`  ${JSON.stringify(other)}: ${name},`);
  }
  const manifest = model.loaded.find(s => s.id === id)?.manifest;
  const needs = Object.fromEntries(Object.entries(manifest?.needs ?? {}).map(([k, t]) => [k, t.name]));
  const uses = Object.fromEntries(Object.entries(manifest?.uses ?? {}).map(([k, t]) => [k, t.name]));
  lines.push(
    '',
    `export const id = ${JSON.stringify(id)};`,
    `export const halves = { ${halves.join(', ')} } as const;`,
    '/** The `contract/testing` module of every package this one consumes, by id. Nothing else is loaded. */',
    `export const contractTesting: Readonly<Record<string, Record<string, unknown>>> = {\n${fakes.join('\n')}\n};`,
    `export const consumes: readonly string[] = ${JSON.stringify(consumed)};`,
    `export const needs: Readonly<Record<string, string>> = ${JSON.stringify(needs)};`,
    `export const uses: Readonly<Record<string, string>> = ${JSON.stringify(uses)};`,
    `export const contractHashes = ${hashesLiteral(model, [id, ...consumed])};`,
    '',
  );
  return new Map([[outRel, lines.join('\n')]]);
}

/** Paths whose on-disk content differs from `files` (missing files count only when `missingIsStale`). */
export function staleFiles(root: string, files: ReadonlyMap<string, string>, missingIsStale: boolean): string[] {
  const stale: string[] = [];
  for (const [rel, content] of files) {
    const path = join(root, rel);
    if (!existsSync(path)) {
      if (missingIsStale) stale.push(`${rel} (missing)`);
      continue;
    }
    if (readFileSync(path, 'utf8') !== content) stale.push(rel);
  }
  return stale;
}

export function writeFiles(root: string, files: ReadonlyMap<string, string>): void {
  for (const [rel, content] of files) {
    const path = join(root, rel);
    mkdirSync(dirname(path), { recursive: true });
    if (existsSync(path) && readFileSync(path, 'utf8') === content) continue;
    writeFileSync(path, content);
  }
}

function argValue(args: readonly string[], flag: string): string | undefined {
  const at = args.indexOf(flag);
  return at === -1 ? undefined : args[at + 1];
}

async function main(args: readonly string[]): Promise<number> {
  const root = argValue(args, '--root') ?? join(import.meta.dir, '..', '..');
  const only = argValue(args, '--package');
  const model = await buildModel(root, false);
  for (const failure of model.failures) console.error(`⚠️  ${failure}`);
  const files = only === undefined ? generateGlobal(model) : generatePackage(model, only);
  if (args.includes('--check')) {
    const stale = staleFiles(model.ws.root, files, false);
    for (const rel of stale) console.error(`❌ registries-fresh: ${rel} differs from a fresh generation`);
    return stale.length === 0 ? 0 : 1;
  }
  writeFiles(model.ws.root, files);
  console.log(`generated ${[...files.keys()].join(', ')}`);
  return model.failures.length === 0 ? 0 : 1;
}

if (import.meta.main) process.exit(await main(process.argv.slice(2)));
